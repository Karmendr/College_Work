// 2. C Program to Declaring Variable and Printing its Value.

#include<stdio.h>

void main()
{
    int n1 = 2;
    printf("Value of n1 :- %d",n1);
    float n2 = 3.14;
    printf("\nValue of n2 :- %f",n2);
    char ch = 'a';
    printf("\nValue of Ch :- %c",ch);
    double n3 = 3.1424354377;
    printf("\nValue of n3 :- %.10f",n3);  
}