// C/C++ program to find given number is equal or not.


#include<stdio.h>

void main()
{
    int n1,n2;
    printf("Enter first Number :- ");
    scanf("%d",&n1);
    printf("Enter second Number :- ");
    scanf("%d",&n2);

    if(n1==n2) printf("Number is Equal");
    else printf("Number is not Equal");
}