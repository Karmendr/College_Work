#include<stdio.h>

int main()
{
    int a = 12;
    printf("Value of a(Integer) is %d",a);
    char ch = 'K';
    printf("\nValue of ch(Character) is %c",ch);
    float b = 12.98;
    printf("\nValue of b(Float) is %f",b);
    double c = 14.766382386; // 15 decimal places
    printf("\nValue of c(double) is %lf",c);
    long double d = 12.5445434543434434; // 19 decimal places
    printf("\n Value of d(long double) is %f",d);

    return 0;
}